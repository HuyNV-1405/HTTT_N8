-- 1. TẠO CÁC ENUMS (KIỂU DỮ LIỆU ĐẶC THÙ)
CREATE TYPE "Role" AS ENUM ('ADMIN', 'QUAN_LY_KHO', 'NHAN_VIEN_KHO', 'NHAN_VIEN_MUA_HANG', 'NHAN_VIEN_BAN_HANG');
CREATE TYPE "UserStatus" AS ENUM ('ACTIVE', 'INACTIVE');
CREATE TYPE "TrangThaiViTri" AS ENUM ('EMPTY', 'PARTIAL', 'FULL', 'MAINTENANCE');
CREATE TYPE "TrangThaiPhieu" AS ENUM ('PENDING', 'APPROVED', 'REJECTED');
CREATE TYPE "LoaiChuyenKho" AS ENUM ('NOI_BO_KHO', 'LIEN_KHO');
CREATE TYPE "TrangThaiKiemKe" AS ENUM ('DANG_KIEM_KE', 'DA_CAN_BANG', 'DA_HUY');
CREATE TYPE "LoaiCanhBao" AS ENUM ('HET_HANG', 'DUOI_MUC_TOI_THIEU', 'VUOT_MUC_TOI_DA', 'CHENH_LECH_KIEM_KE');
CREATE TYPE "TrangThaiCanhBao" AS ENUM ('CHUA_XU_LY', 'DA_XU_LY');

-- 2. BẢNG NGƯỜI DÙNG & PHÂN QUYỀN
CREATE TABLE "users" (
    "id" TEXT PRIMARY KEY,
    "maNV" TEXT UNIQUE NOT NULL,
    "username" TEXT UNIQUE NOT NULL,
    "password" TEXT NOT NULL,
    "hoTen" TEXT NOT NULL,
    "email" TEXT UNIQUE,
    "sdt" TEXT,
    "role" "Role" NOT NULL DEFAULT 'NHAN_VIEN_KHO',
    "trangThai" "UserStatus" NOT NULL DEFAULT 'ACTIVE',
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. BẢNG ĐỐI TÁC: NHÀ CUNG CẤP & KHÁCH HÀNG
CREATE TABLE "nha_cung_cap" (
    "id" TEXT PRIMARY KEY,
    "maNCC" TEXT UNIQUE NOT NULL,
    "tenNCC" TEXT NOT NULL,
    "sdt" TEXT NOT NULL,
    "email" TEXT,
    "diaChi" TEXT,
    "nguoiLienHe" TEXT,
    "trangThai" BOOLEAN NOT NULL DEFAULT true,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "khach_hang" (
    "id" TEXT PRIMARY KEY,
    "maKH" TEXT UNIQUE NOT NULL,
    "tenKH" TEXT NOT NULL,
    "sdt" TEXT NOT NULL,
    "email" TEXT,
    "diaChi" TEXT,
    "trangThai" BOOLEAN NOT NULL DEFAULT true,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. BẢNG DANH MỤC & HÀNG HÓA
CREATE TABLE "loai_hang" (
    "id" TEXT PRIMARY KEY,
    "maLoai" TEXT UNIQUE NOT NULL,
    "tenLoai" TEXT NOT NULL,
    "moTa" TEXT,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "hang_hoa" (
    "id" TEXT PRIMARY KEY,
    "maHH" TEXT UNIQUE NOT NULL,
    "tenHH" TEXT NOT NULL,
    "donViTinh" TEXT NOT NULL,
    "giaNhap" DECIMAL(15,2) NOT NULL DEFAULT 0,
    "giaXuat" DECIMAL(15,2) NOT NULL DEFAULT 0,
    "dinhMucToiThieu" INTEGER NOT NULL DEFAULT 10,
    "dinhMucToiDa" INTEGER NOT NULL DEFAULT 1000,
    "hinhAnh" TEXT,
    "moTa" TEXT,
    "trangThai" BOOLEAN NOT NULL DEFAULT true,
    "loaiHangId" TEXT NOT NULL REFERENCES "loai_hang"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
    "nhaCungCapId" TEXT REFERENCES "nha_cung_cap"("id") ON DELETE SET NULL ON UPDATE CASCADE,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. BẢNG HỆ THỐNG KHO & SƠ ĐỒ VỊ TRÍ LƯU TRỮ
CREATE TABLE "kho" (
    "id" TEXT PRIMARY KEY,
    "maKho" TEXT UNIQUE NOT NULL,
    "tenKho" TEXT NOT NULL,
    "diaChi" TEXT NOT NULL,
    "nguoiQuanLyId" TEXT REFERENCES "users"("id") ON DELETE SET NULL ON UPDATE CASCADE,
    "trangThai" BOOLEAN NOT NULL DEFAULT true,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE "khu_vuc" (
    "id" TEXT PRIMARY KEY,
    "maKhuVuc" TEXT NOT NULL,
    "tenKhuVuc" TEXT NOT NULL,
    "khoId" TEXT NOT NULL REFERENCES "kho"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    "moTa" TEXT,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "khu_vuc_khoId_maKhuVuc_key" UNIQUE ("khoId", "maKhuVuc")
);

CREATE TABLE "vi_tri_luu_tru" (
    "id" TEXT PRIMARY KEY,
    "maViTri" TEXT UNIQUE NOT NULL,
    "khoId" TEXT NOT NULL REFERENCES "kho"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    "khuVucId" TEXT NOT NULL REFERENCES "khu_vuc"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    "ke" TEXT NOT NULL,
    "tang" TEXT NOT NULL,
    "o" TEXT NOT NULL,
    "sucChua" INTEGER NOT NULL DEFAULT 100,
    "trangThai" "TrangThaiViTri" NOT NULL DEFAULT 'EMPTY',
    "moTa" TEXT,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. BẢNG SỔ TỒN KHO THEO VỊ TRÍ
CREATE TABLE "ton_kho" (
    "id" TEXT PRIMARY KEY,
    "khoId" TEXT NOT NULL REFERENCES "kho"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    "hangHoaId" TEXT NOT NULL REFERENCES "hang_hoa"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    "viTriId" TEXT NOT NULL REFERENCES "vi_tri_luu_tru"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    "soLuongTon" INTEGER NOT NULL DEFAULT 0,
    "soLuongKhaDung" INTEGER NOT NULL DEFAULT 0,
    "soLuongTamGiu" INTEGER NOT NULL DEFAULT 0,
    "ngayCapNhat" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "ton_kho_khoId_hangHoaId_viTriId_key" UNIQUE ("khoId", "hangHoaId", "viTriId")
);

-- 7. BẢNG PHIẾU NHẬP KHO & CHI TIẾT
