    "nguoiDuyetId" TEXT REFERENCES "users"("id") ON DELETE SET NULL ON UPDATE CASCADE,
    "ngayDuyet" TIMESTAMP(3),
    "trangThai" "TrangThaiPhieu" NOT NULL DEFAULT 'PENDING',
    "ketQuaKiemTra" TEXT,
    "tongTien" DECIMAL(15,2) NOT NULL DEFAULT 0,
    "ghiChu" TEXT,
    "ngayTao" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
